import XCTest
@testable import EEGCore

final class TrialPlanAssociationTests: XCTestCase {
    // Enumerate complete bit masks independently of the production state recurrence.
    private func enumerate(outcomes: [Bool], tasks: Int, maximumRun: Int) -> [UInt64] {
        var counts = [UInt64](repeating: 0, count: tasks + 1)
        for mask in 0..<(1 << outcomes.count) where mask.nonzeroBitCount == tasks {
            let assignment = outcomes.indices.map { mask & (1 << $0) != 0 }
            var accepted = true
            if maximumRun < assignment.count {
                for start in 0..<(assignment.count - maximumRun) {
                    if Set(assignment[start...start + maximumRun]).count == 1 { accepted = false }
                }
            }
            if accepted {
                let score = zip(assignment, outcomes).filter { $0 && $1 }.count
                counts[score] += 1
            }
        }
        return counts
    }
    func testDistributionMatchesExhaustiveWholeTrialAssignments() throws {
        for n in 2...8 {
            for mask in 0..<(1 << n) {
                let outcomes = (0..<n).map { mask & (1 << $0) != 0 }
                for run in [1, 2, 3] {
                    XCTAssertEqual(try EEGTrialPlanAssociation.distribution(outcomes: outcomes,
                        taskCount: n / 2, maximumRun: run),
                        enumerate(outcomes: outcomes, tasks: n / 2, maximumRun: run))
                }
            }
        }
    }
    func testActualPlanKeepsIdentityAndReturnsConservativeTies() throws {
        let plan = try EEGTrialPlan(sessionID: "s", participantID: "p", seed: 42)
        for value in [false, true] {
            let outcomes = Dictionary(uniqueKeysWithValues: plan.trials.map { ($0.id, value) })
            let result = try EEGTrialPlanAssociation.run(plan: plan, candidateObserved: outcomes)
            XCTAssertEqual(result.conditionalUpperTail, 1)
            XCTAssertEqual(result.admissibleSchedules, result.atLeastObservedSchedules)
            XCTAssertEqual(result.orderedTrialIDs, plan.trials.map(\.id))
            XCTAssertEqual(result.planSeed, "42")
            XCTAssertEqual(result.candidateObserved, [Bool](repeating: value, count: 24))
            XCTAssertEqual(result.status, "conditional_only_exchangeability_unverified")
            XCTAssertEqual(result, try JSONDecoder().decode(EEGTrialPlanAssociation.Result.self,
                from: JSONEncoder().encode(result)))
        }
    }
    func testV1CountsMatchIndependentEnumerationAndDictionaryOrderDoesNotMatter() throws {
        let plan = try EEGTrialPlan(sessionID: "s", participantID: "p", seed: 42)
        let pairs = plan.trials.enumerated().map { ($0.element.id, $0.offset < 12) }
        let result = try EEGTrialPlanAssociation.run(plan: plan, candidateObserved: Dictionary(uniqueKeysWithValues: pairs))
        XCTAssertEqual(result, try EEGTrialPlanAssociation.run(plan: plan,
            candidateObserved: Dictionary(uniqueKeysWithValues: pairs.reversed())))
        // Fixed count vector generated by tools/check_trial_plan_association.py.
        XCTAssertEqual(result.scheduleCountsByTaskCandidateTrials,
                       [0, 0, 0, 380, 21281, 169490, 323680, 169490, 21281, 380, 0, 0, 0])
    }
    func testPerfectSyntheticAssociationCountsObservedAssignmentAndAllTies() throws {
        let plan = try EEGTrialPlan(sessionID: "s", participantID: "p", seed: 42)
        let outcomes = Dictionary(uniqueKeysWithValues: plan.trials.map {
            ($0.id, $0.requestedCondition == .silentSerialSubtraction)
        })
        let result = try EEGTrialPlanAssociation.run(plan: plan, candidateObserved: outcomes)
        XCTAssertEqual(result.observedTaskCandidateTrials, 12)
        XCTAssertEqual(result.atLeastObservedSchedules, 1)
        XCTAssertEqual(result.admissibleSchedules, 705982)
        XCTAssertEqual(result.conditionalUpperTail, 1.0 / 705982, accuracy: 1e-15)
        let opposite = try EEGTrialPlanAssociation.run(plan: plan,
            candidateObserved: outcomes.mapValues { !$0 })
        XCTAssertEqual(opposite.observedTaskCandidateTrials, 0)
        XCTAssertEqual(opposite.conditionalUpperTail, 1)
    }
    func testRejectsUnavailableExtraneousAndControlPlanOutcomes() throws {
        let plan = try EEGTrialPlan(sessionID: "s", participantID: "p", seed: 42)
        var rows = Dictionary(uniqueKeysWithValues: plan.trials.map { ($0.id, false) })
        rows.removeValue(forKey: plan.trials[0].id)
        XCTAssertThrowsError(try EEGTrialPlanAssociation.run(plan: plan, candidateObserved: rows))
        rows["foreign-trial"] = false
        XCTAssertThrowsError(try EEGTrialPlanAssociation.run(plan: plan, candidateObserved: rows))
        rows[plan.trials[0].id] = false
        XCTAssertThrowsError(try EEGTrialPlanAssociation.run(plan: plan, candidateObserved: rows))
        let controls = try EEGTrialPlan(sessionID: "s", participantID: "p", seed: 42, controls: true)
        XCTAssertThrowsError(try EEGTrialPlanAssociation.run(plan: controls, candidateObserved: [:]))
    }
    func testCancellationDoesNotPublishAResult() async {
        let job = Task {
            withUnsafeCurrentTask { $0?.cancel() }
            do {
                let plan = try EEGTrialPlan(sessionID: "s", participantID: "p", seed: 42)
                _ = try EEGTrialPlanAssociation.run(plan: plan,
                    candidateObserved: Dictionary(uniqueKeysWithValues: plan.trials.map { ($0.id, false) }))
                return false
            } catch is CancellationError { return true }
            catch { return false }
        }
        let cancelled = await job.value
        XCTAssertTrue(cancelled)
    }
}
