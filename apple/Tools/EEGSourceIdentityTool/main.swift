import Foundation
import CryptoKit

// Build-only tool. No git, network, headset, user recordings or runtime dependency.
let arguments = Array(CommandLine.arguments.dropFirst())
guard arguments.count >= 3 else { fatalError("Expected package root, output and source inputs") }
let root = URL(fileURLWithPath: arguments[0]).standardizedFileURL.path + "/"
let output = URL(fileURLWithPath: arguments[1])
var inputs = [(String, Data)]()
for path in arguments.dropFirst(2) {
    let url = URL(fileURLWithPath: path).standardizedFileURL
    guard url.path.hasPrefix(root) else { fatalError("Source outside package root") }
    inputs.append((String(url.path.dropFirst(root.count)), try Data(contentsOf: url)))
}
inputs.sort { $0.0 < $1.0 }
guard Set(inputs.map(\.0)).count == inputs.count else { fatalError("Duplicate source input") }
var hash = SHA256()
func appendField(_ data: Data) {
    var length = UInt64(data.count).bigEndian
    withUnsafeBytes(of: &length) { hash.update(data: Data($0)) }
    hash.update(data: data)
}
appendField(Data("eeg.core-source.v1".utf8))
for (name, data) in inputs { appendField(Data(name.utf8)); appendField(data) }
let digest = hash.finalize().map { String(format: "%02x", $0) }.joined()
let generated = """
// Generated by EEGSourceIdentityTool. Do not edit.
public enum EEGSourceIdentity {
    public static let schema = "eeg.core-source.v1"
    public static let sha256 = "\(digest)"
    public static let inputFileCount = \(inputs.count)
}

"""
try FileManager.default.createDirectory(at: output.deletingLastPathComponent(), withIntermediateDirectories: true)
let bytes = Data(generated.utf8)
if (try? Data(contentsOf: output)) != bytes { try bytes.write(to: output, options: .atomic) }
